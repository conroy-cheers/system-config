#!/usr/bin/env python3
"""Generate disabled-drm.nix from configs built with and without DRM."""

import argparse
import pathlib
import re


CORE = {
    "DRM",
    "DRM_AUX_BRIDGE",
    "DRM_AUX_HPD_BRIDGE",
    "DRM_BRIDGE",
    "DRM_GEM_DMA_HELPER",
    "DRM_KMS_HELPER",
    "DRM_PANEL",
    "DRM_PANEL_BRIDGE",
    "DRM_PANEL_ORIENTATION_QUIRKS",
    "DRM_SSD16XX",
}


def enabled(path: pathlib.Path) -> set[str]:
    result = set()
    for line in path.read_text().splitlines():
        match = re.fullmatch(r"CONFIG_([A-Z0-9_]+)=[ym]", line)
        if match:
            result.add(match.group(1))
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("baseline", type=pathlib.Path)
    parser.add_argument("epaper", type=pathlib.Path)
    args = parser.parse_args()

    symbols = sorted(enabled(args.epaper) - enabled(args.baseline) - CORE)
    print("# Generated by update-disabled-drm.py; review changes before committing.")
    print("[")
    for symbol in symbols:
        print(f'  "{symbol}"')
    print("]")


if __name__ == "__main__":
    main()
